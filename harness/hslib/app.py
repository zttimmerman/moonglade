"""`harness/hs app`: build dist/Hearthstone.app (openspec/changes/launcher-app, task 2.1; design.md "Bundle shape").

    dist/Hearthstone.app/Contents/
        Info.plist                 CFBundleExecutable Hearthstone, CFBundleIdentifier local.hearthstone.app,
                                   CFBundleIconFile AppIcon, LSMinimumSystemVersion = this Mac's macOS version
        MacOS/Hearthstone          the launcher (harness/app/launcher.m, compiled here with clang)
        Resources/AppIcon.icns     copied from branding/ (generated by `harness/hs icon`)
        Resources/repo-path        this repo's absolute path, so a copy of the app anywhere still finds it
        Resources/python-dir       the directory of the python3 that ./play should use (LaunchServices starts apps
                                   with PATH=/usr/bin:/bin:/usr/sbin:/sbin, whose python3 is too old)
        _CodeSignature/            ad-hoc signature (`codesign -s -`, designated requirement = the bundle identifier;
                                   see DESIGNATED), checked with `codesign --verify --deep --strict`

Writes only inside the repo: the bundle is assembled in dist/.build/ and moved into place; compiler and codesign
temp files go to env/app-build/tmp (TMPDIR), which is removed afterwards. Nothing is installed anywhere; Zach drags
the app to /Applications or the Dock himself if he wants. `app.bundle_valid` runs this under a sandbox profile that
denies every file write outside the repo.
"""
from __future__ import annotations

import os
import plistlib
import shutil
import subprocess
import sys
from pathlib import Path

from . import icon, paths as P

DIST = P.ROOT / "dist"
APP = DIST / "Hearthstone.app"
SOURCE = P.HARNESS / "app" / "launcher.m"
EXE_NAME = "Hearthstone"
BUNDLE_ID = "local.hearthstone.app"
TMP = P.ENV / "app-build" / "tmp"
LOG = P.LOGS / "app.log"
HOOK_ENV = "HS_APP_TEST_HOOK"
# Explicit designated requirement. An ad-hoc signature's default one is the code hash, which changes whenever the
# launcher or plist changes; macOS privacy grants (TCC: the "Documents folder" permission the play loop needs, since
# the repo lives in ~/Documents) are tied to the designated requirement, so every rebuild would ask again. Pinning it
# to the bundle identifier keeps one "Allow" valid across rebuilds and copies. Weaker identity (any code signed with
# this identifier matches), acceptable for a personal, never-distributed app.
DESIGNATED = f'designated => identifier "{BUNDLE_ID}"'
DEPLOYMENT_TARGET = "13.0"     # the launcher uses nothing newer; LSMinimumSystemVersion still pins this Mac's version


class AppBuildError(Exception):
    def __init__(self, msg: str, evidence: dict | None = None):
        super().__init__(msg)
        self.evidence = evidence or {}


def _run(cmd: list, env: dict, ev: dict, what: str) -> str:
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True, env=env)
    ev.setdefault("commands", []).append({"cmd": " ".join(map(str, cmd)), "rc": r.returncode,
                                          "output": (r.stdout + r.stderr)[-1500:]})
    if r.returncode != 0:
        raise AppBuildError(f"{what} failed (rc {r.returncode}): {(r.stderr or r.stdout).strip()[-800:]}", ev)
    return r.stdout


def host_version() -> str:
    v = subprocess.run(["/usr/bin/sw_vers", "-productVersion"], capture_output=True, text=True).stdout.strip()
    return ".".join((v.split(".") + ["0"])[:2])


def python_dir() -> str:
    """Directory of the python3 on this shell's PATH (what ./play's `exec python3` finds), if it's new enough."""
    exe = shutil.which("python3")
    if not exe:
        raise AppBuildError("no python3 on PATH")
    r = subprocess.run([exe, "-c", "import sys; print(sys.version_info >= (3, 10))"], capture_output=True, text=True)
    if r.stdout.strip() != "True":
        raise AppBuildError(f"{exe} is older than Python 3.10; the harness needs 3.10+")
    return str(Path(exe).parent)


def info_plist() -> dict:
    return {
        "CFBundleDevelopmentRegion": "en",
        "CFBundleDisplayName": "Hearthstone",
        "CFBundleExecutable": EXE_NAME,
        "CFBundleIconFile": "AppIcon",
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleName": "Hearthstone",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": "0.1",
        "CFBundleVersion": "1",
        "LSApplicationCategoryType": "public.app-category.role-playing-games",
        "LSMinimumSystemVersion": host_version(),
        "NSHighResolutionCapable": True,
        "NSHumanReadableCopyright": "Personal project; not for redistribution.",
    }


def build() -> dict:
    """Build dist/Hearthstone.app. Returns evidence (paths, commands, plist)."""
    ev: dict = {"app": str(APP)}
    if not icon.ICNS_OUT.is_file():
        raise AppBuildError(f"{icon.ICNS_OUT} missing; run `harness/hs icon`", ev)
    stage = DIST / ".build" / "Hearthstone.app"
    shutil.rmtree(stage.parent, ignore_errors=True)
    TMP.mkdir(parents=True, exist_ok=True)
    env = {**os.environ, "TMPDIR": str(TMP) + "/"}
    try:
        contents = stage / "Contents"
        (contents / "MacOS").mkdir(parents=True)
        (contents / "Resources").mkdir()
        sdk = _run(["/usr/bin/xcrun", "--show-sdk-path"], env, ev, "xcrun --show-sdk-path").strip()
        # -isysroot explicitly: stray headers in /usr/local/include otherwise shadow the SDK's
        _run(["/usr/bin/clang", "-isysroot", sdk, "-fobjc-arc", "-O2", "-Wall", "-Werror",
              f"-mmacosx-version-min={DEPLOYMENT_TARGET}", "-framework", "Cocoa", SOURCE,
              "-o", contents / "MacOS" / EXE_NAME], env, ev, "compiling the launcher")
        with open(contents / "Info.plist", "wb") as f:
            plistlib.dump(info_plist(), f, fmt=plistlib.FMT_XML, sort_keys=True)
        (contents / "PkgInfo").write_text("APPL????")
        shutil.copyfile(icon.ICNS_OUT, contents / "Resources" / "AppIcon.icns")
        (contents / "Resources" / "repo-path").write_text(str(P.ROOT.resolve()) + "\n")
        (contents / "Resources" / "python-dir").write_text(python_dir() + "\n")
        _run(["/usr/bin/codesign", "--force", "--sign", "-", "--timestamp=none", f"-r={DESIGNATED}", stage],
             env, ev, "codesign")
        _run(["/usr/bin/codesign", "--verify", "--deep", "--strict", stage], env, ev, "codesign --verify")
        if APP.exists():
            shutil.rmtree(APP)
        DIST.mkdir(exist_ok=True)
        stage.rename(APP)
    finally:
        shutil.rmtree(DIST / ".build", ignore_errors=True)
        shutil.rmtree(TMP.parent, ignore_errors=True)
    ev |= {"plist": info_plist(), "repo_path": str(P.ROOT.resolve()), "python": sys.version.split()[0]}
    return ev


def cli() -> int:
    from .util import log
    import json
    try:
        ev = build()
    except AppBuildError as e:
        log(f"APP BUILD FAILED: {e}")
        return 1
    print(json.dumps({k: ev[k] for k in ("app", "repo_path", "plist")}, indent=2))
    log(f"Built {APP}. Double-click it in Finder, or drag it to /Applications or the Dock.")
    return 0
